#include <stdio.h> 
int main() { 
 
const float PI = 3.14159; 

int age = 25;            
char grade = 'A';        
float height = 5.9;      
// Integer variable 
// Character variable 
// Floating point variable 
// Displaying the values 
printf("----- Variable and Constant Example in C -----\n"); 
printf("Integer value (age): %d\n", age); 
printf("Character value (grade): %c\n", grade); 
printf("Float value (height): %.2f\n", height); 
printf("Constant value (PI): %.5f\n", PI); 
return 0; 
}
